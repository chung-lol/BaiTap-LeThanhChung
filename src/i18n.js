// Follows the device language: Vietnamese -> 'vi', anything else -> 'en'.
export function useI18n() {
  const locales = useLocales();
  const lang = locales[0]?.languageCode === 'vi' ? 'vi' : 'en';
  return useMemo(() => ({ lang, t: (key) => translations[lang][key] ?? key }), [lang]);
}
